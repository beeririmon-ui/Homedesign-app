/**
 * Legal pages: working drafts, so the structure, links and accessibility exist from day one. Every text here needs
 * review by a lawyer before launch (docs/architecture.md, "רשימת השקה בישראל"). Nothing here is verified.
 */
import type { ComponentChildren } from 'preact';

type Page = 'accessibility' | 'terms' | 'privacy' | 'returns';

const TITLES: Record<Page, string> = {
  accessibility: 'הצהרת נגישות',
  terms: 'תקנון האתר',
  privacy: 'מדיניות פרטיות',
  returns: 'ביטול עסקה, החזרות והחלפות',
};

function Draft() {
  return <p class="notice warn">טיוטת עבודה. הנוסח לא נבדק משפטית ולא אומת. שם העסק, הכתובת ופרטי הקשר יושלמו לפני ההשקה.</p>;
}

export function Legal({ page }: { page: Page }) {
  let body: ComponentChildren;
  switch (page) {
    case 'accessibility':
      body = (
        <>
          <p>אנחנו רוצים שכל אחד ואחת יוכלו לטייל בבית, לבחור מוצרים ולקנות, גם עם קורא מסך, מקלדת בלבד, הגדלה או ניגודיות גבוהה.</p>
          <h2>רמת הנגישות</h2>
          <p>
            האתר נבנה לפי התקן הישראלי ת"י 5568 (המבוסס על הנחיות WCAG) ברמה AA. בכל שינוי באתר רצות בדיקות אוטומטיות (axe), ואנחנו בודקים גם ידנית עם מקלדת
            וקורא מסך.
          </p>
          <h2>מה עשינו</h2>
          <ul>
            <li>כל נקודה בחדר היא כפתור אמיתי עם שם ברור, ויש גם רשימה מלאה של הפריטים מתחת לחדר.</li>
            <li>גלגל הווריאציות עובד במקלדת (חיצים, Home, End, Enter, Escape), במגע ובעכבר.</li>
            <li>מי שביקש להפחית תנועה במכשיר מקבל מעברים מיידיים, בלי זום ובלי סרטוני מעבר.</li>
            <li>ניגודיות טקסט של 4.5:1 לפחות, במצב בהיר ובמצב כהה.</li>
            <li>טפסים עם תוויות, הודעות שגיאה ליד כל שדה וסיכום שגיאות בראש הטופס.</li>
          </ul>
          <h2>מגבלות ידועות</h2>
          <p>התמונות באתר זמניות בשלב ההקמה. תיאור חלופי מלא לכל תמונה יתווסף עם התמונות הסופיות.</p>
          <h2>רכז/ת נגישות</h2>
          <p>שם, טלפון ואימייל יושלמו לפני ההשקה. נשמח לשמוע על כל קושי ונחזור תוך 5 ימי עסקים.</p>
          <p class="small muted">עדכון אחרון של ההצהרה: טיוטה, אוקטובר 2026.</p>
        </>
      );
      break;
    case 'returns':
      body = (
        <>
          <p>לפי חוק הגנת הצרכן ותקנות ביטול עסקה (הנוסח הסופי ייבדק על ידי עורך דין):</p>
          <ul>
            <li>אפשר לבטל עסקה תוך 14 יום מיום קבלת המוצר או מסמך פרטי העסקה, המאוחר מביניהם.</li>
            <li>דמי ביטול: עד 5% מהמחיר או ₪100, הנמוך מביניהם, אלא אם הביטול נובע מפגם או מאי התאמה.</li>
            <li>מוצר שנפגם או שאינו תואם להזמנה: החזר מלא, כולל עלות המשלוח.</li>
            <li>ההחזר הכספי יבוצע תוך 14 יום מקבלת הודעת הביטול, באמצעי התשלום שבו שולם.</li>
          </ul>
          <p>להודעת ביטול: באימייל או בטלפון של שירות הלקוחות (יושלמו לפני ההשקה). יש לציין את מספר ההזמנה.</p>
        </>
      );
      break;
    case 'privacy':
      body = (
        <>
          <p>אנחנו אוספים רק מה שצריך כדי לספק את ההזמנה: שם, אימייל, טלפון וכתובת למשלוח.</p>
          <ul>
            <li>פרטי אשראי לא נשמרים אצלנו ולא עוברים דרך האתר: התשלום מתבצע בדף של חברת הסליקה.</li>
            <li>הפרטים מועברים רק למי שצריך אותם לביצוע ההזמנה: הספק ושירות המשלוחים, חברת הסליקה ושירות החשבוניות.</li>
            <li>דיוור שיווקי נשלח רק אם סימנתם הסכמה, ואפשר להסיר בכל עת.</li>
            <li>אפשר לבקש לעיין במידע, לתקן אותו או למחוק אותו, לפי חוק הגנת הפרטיות ותיקון 13.</li>
            <li>האתר לא משתמש בעוגיות פרסום. נשמרים בדפדפן רק הסל וההעדפה של ערכת הצבע.</li>
          </ul>
        </>
      );
      break;
    default:
      body = (
        <>
          <p>התקנון מסדיר את השימוש באתר ואת הרכישה בו. הוא חל על כל מי שגולש או קונה באתר.</p>
          <ul>
            <li>המחירים באתר כוללים מע"מ. דמי המשלוח מוצגים לפני התשלום.</li>
            <li>זמני האספקה הם הערכה של הספק, ומוצגים בעמוד כל מוצר ובשלב התשלום.</li>
            <li>תמונות החדר ממחישות את המוצר בבית. פריטי המילוי בתמונות (ענפים, נרות וכדומה) לא כלולים, אלא אם נכתב אחרת.</li>
            <li>
              ביטולים והחזרות: לפי <a href="/returns/">מדיניות הביטולים</a>.
            </li>
          </ul>
        </>
      );
  }
  return (
    <div class="wrap page">
      <article class="prose" aria-labelledby="legal-title">
        <h1 id="legal-title" tabIndex={-1}>
          {TITLES[page]}
        </h1>
        <Draft />
        {body}
      </article>
    </div>
  );
}
